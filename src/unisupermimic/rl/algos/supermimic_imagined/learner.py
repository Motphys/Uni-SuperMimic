class ImaginedSuperMimicLearner:
    """Train policy and critic entirely inside a frozen world model."""

    def __init__(
        self,
        task: G1ImaginedTask,
        cfg: ImaginedSuperMimicConfig,
        log_dir: str | Path,
        device: str | torch.device | None = None,
    ):
        self.task = task
        self.cfg = cfg
        self.mdp = task.mdp
        self.motion = task.motion
        self.wm = task.world_model
        self.wm.requires_grad_(False)
        self.wm.eval()
        self.device = torch.device(device) if device is not None else self.mdp.default_q.device
        if self.device != self.mdp.default_q.device:
            # The task builder places all tensors on the requested device. Refuse a
            # mismatch rather than silently bridge state across devices.
            raise ValueError(
                f"learner device {self.device} does not match task device "
                f"{self.mdp.default_q.device}"
            )

        torch.manual_seed(cfg.seed)
        networks_module.AMP_DTYPE = torch.bfloat16 if cfg.amp == "bf16" else None
        networks_module.RunningNorm.no_sync = cfg.no_sync
        torch.backends.cuda.matmul.allow_tf32 = cfg.amp == "none"
        torch.backends.cudnn.allow_tf32 = True

        self.log_dir = Path(log_dir)
        self.log_dir.mkdir(parents=True, exist_ok=True)
        self.pi = self._make_policy()
        self.critic = Critic(self._critic_input_dim(), hidden=cfg.critic_hidden).to(self.device)
        if cfg.test_hidden_dims is not None:
            self.critic.net = mlp(self.critic.norm.mean.numel(), cfg.test_hidden_dims, 1).to(
                self.device
            )
        if cfg.critic_norm_max_count is not None:
            # The global RunningNorm default is intentionally huge; deployments can freeze
            # earlier without changing the default behavior of existing configs.
            self.critic.norm.max_count = float(cfg.critic_norm_max_count)
        self.pi_avg = None
        if cfg.pi_ema > 0:
            self.pi_avg = AveragedModel(
                self.pi,
                multi_avg_fn=get_ema_multi_avg_fn(cfg.pi_ema),
                use_buffers=True,
            )

        optimizer_mode = self._resolve_optimizer_mode(cfg.optimizer_mode, self.device)
        # Leaving foreach=None under auto preserves Adam's implementation choice;
        # only explicit acceleration modes force foreach or single-tensor kernels.
        foreach = cfg.optimizer_mode in ("foreach", "single") or None
        if cfg.pi_opt == "muon":
            self.opt_pi = MuonAdam(
                self.pi,
                [self.pi.enc, self.pi.dec],
                lr=cfg.lr,
                betas=(0.9, 0.95),
                fused=optimizer_mode == "fused",
            )
        else:
            self.opt_pi = torch.optim.Adam(
                self.pi.parameters(),
                lr=cfg.lr,
                betas=(0.9, 0.95),
                amsgrad=cfg.pi_amsgrad,
                foreach=foreach,
                fused=optimizer_mode == "fused",
            )
        self.opt_v = torch.optim.Adam(
            self.critic.parameters(),
            lr=cfg.lr,
            amsgrad=cfg.critic_amsgrad,
            foreach=foreach,
            fused=optimizer_mode == "fused",
        )

        self._v_mean = torch.zeros((), device=self.device)
        self._v_std = torch.ones((), device=self.device)
        self._v_ema = 0.01
        self._v_init = False

        self.iteration = 0
        self.wall_time = 0.0
        self.imag_steps = 0
        self._state: State | None = None
        self._obs_hist: torch.Tensor | None = None
        self._previous_action: torch.Tensor | None = None
        self._context: torch.Tensor | None = None
        self._normalized_context: torch.Tensor | None = None
        self._frames: torch.Tensor | None = None
        self._ep_step: torch.Tensor | None = None

        self._reset_position_noise = torch.tensor(
            [-0.05, -0.05, -0.01, 0.05, 0.05, 0.01], device=self.device
        ).view(2, 3)
        self._reset_rotation_noise = torch.tensor(
            [-0.1, -0.1, -0.2, 0.1, 0.1, 0.2], device=self.device
        ).view(2, 3)
        self._reset_velocity_noise = torch.tensor(
            [-0.5, -0.5, -0.2, 0.5, 0.5, 0.2], device=self.device
        ).view(2, 3)
        self._reset_angular_noise = torch.tensor(
            [-0.52, -0.52, -0.78, 0.52, 0.52, 0.78], device=self.device
        ).view(2, 3)

        self._fused_scoring = hasattr(self.mdp, "reward_term_critic_features_with_reference")
        self._detach_frozen_wm = True
        self._compile_fns()
        self.reset_all()

    def _make_policy(self) -> Policy:
        return Policy(
            obs_dim=self.mdp.obs_dim,
            goal_dim=self.mdp.goal_frame_dim * self.cfg.goal_frames,
            hist=self.cfg.hist,
            z_dim=self.cfg.z_dim,
            num_joints=self.mdp.num_joints,
            hidden=self.cfg.policy_hidden,
        ).to(self.device)

    def _critic_input_dim(self) -> int:
        features = self.mdp.critic_features(
            self.motion.ref_state(torch.zeros(1, dtype=torch.long, device=self.device)),
            torch.zeros(1, dtype=torch.long, device=self.device),
            torch.zeros(1, self.mdp.context_dim, device=self.device),
        )
        return features.shape[-1] + self.mdp.goal_frame_dim * self.cfg.goal_frames

    def _compile_fns(self) -> None:
        if not self.cfg.compile:
            self._imag_policy_fn = self.pi
            self._imag_state_fn = self.wm.step
            self._reward_fn = self._reward_term
            self._fused_score_fn = self._reward_term_critic_features
            self._critic_input_fn = self._critic_input
            self._critic_targets_fn = self._critic_targets
            self._critic_loss_fn = self._critic_loss
            return

        # Keep each compiled region narrowly scoped. The policy function is the
        # only rollout component that needs autograd; compiling it separately from
        # the frozen state transition avoids specializing the whole imagination
        # graph (including the horizon loop) and prevents an inference-mode WM
        # compilation from being reused for a training-mode call.
        self._imag_policy_fn = torch.compile(self.pi, dynamic=False)
        self._imag_state_fn = torch.compile(self.wm.step, dynamic=False)
        self._reward_fn = torch.compile(self._reward_term, dynamic=False)
        self._fused_score_fn = torch.compile(self._reward_term_critic_features, dynamic=False)
        self._critic_input_fn = torch.compile(self._critic_input, dynamic=False)
        self._critic_targets_fn = torch.compile(self._critic_targets, dynamic=False)
        self._critic_loss_fn = torch.compile(self._critic_loss, dynamic=False)

    def _sample_valid_frames(self, batch: int) -> torch.Tensor:
        """Draw frame indices that retain at least ``horizon`` frames in their clip."""
        clip_start = self.motion.clip_start.detach().to(self.device)
        clip_end = self.motion.clip_end.detach().to(self.device)
        # valid Imagination starts satisfy frame + horizon <= clip_end.
        lengths = clip_end - clip_start - self.cfg.horizon + 1
        valid = lengths > 0
        if not bool(valid.any()):
            raise ValueError(
                f"no motion clip is long enough for imagination horizon {self.cfg.horizon}"
            )
        starts = clip_start[valid]
        lengths = lengths[valid]
        cumulative = lengths.cumsum(0)
        draws = torch.rand(batch, device=self.device) * cumulative[-1]
        clip_ids = torch.searchsorted(cumulative, draws, right=True).clamp(
            max=clip_start.numel() - 1
        )
        offsets = torch.floor(
            torch.rand(batch, device=self.device) * lengths.gather(0, clip_ids)
        ).long()
        return starts.gather(0, clip_ids) + offsets

    def _reset_batch(self, indices: torch.Tensor | None = None) -> torch.Tensor:
        """Reset all or selected imagined environments to motion-library starts."""
        if indices is None:
            batch = self.cfg.batch
            selected = None
        else:
            if indices.ndim != 1:
                raise ValueError("reset indices must be one-dimensional")
            batch = int(indices.numel())
            selected = indices
            reset_mask = torch.zeros(self.cfg.batch, dtype=torch.bool, device=self.device)
            reset_mask[selected] = True
        if batch == 0:
            return torch.zeros(0, dtype=torch.bool, device=self.device)

        if hasattr(self.mdp, "valid_imagination_start"):
            # Resample rather than clamp: a rollout must never query beyond its
            # owning clip, and rejection preserves the original start distribution
            # conditioned on being horizon-valid.
            maximum = max(self.motion.num_frames - self.cfg.horizon - 1, 0)
            frames = torch.randint(0, maximum + 1, (batch,), device=self.device)
            valid = self.mdp.valid_imagination_start(frames, self.cfg.horizon)
            if bool((~valid).any()):
                overflow = (~valid).nonzero(as_tuple=False).squeeze(-1)
                replacement = self._sample_valid_frames(overflow.numel())
                frames = frames.clone()
                frames[overflow] = replacement
        else:
            frames = torch.randint(0, self.motion.num_frames, (batch,), device=self.device)
        state = self.motion.ref_state(frames)
        context = torch.zeros((batch, self.mdp.context_dim), device=self.device)
        if self.cfg.reset_noise:
            context[:, 0] = torch.rand(batch, device=self.device) * 0.9 + 0.3
            context[:, 1:30] = torch.rand((batch, 29), device=self.device) * 0.02 - 0.01
            context[:, 30:33] = torch.rand((batch, 3), device=self.device) * 2 - 1
            context[:, 30:33] *= torch.tensor([0.025, 0.05, 0.05], device=self.device)
            position, rotation, velocity, angular, joints = (
                state[0],
                state[1],
                state[2],
                state[3],
                state[4],
            )
            position = _uniform_like(
                position, self._reset_position_noise[0], self._reset_position_noise[1]
            )
            rotation_noise = _uniform_like(
                angular, self._reset_rotation_noise[0], self._reset_rotation_noise[1]
            )
            rotation = _so3_exp(rotation_noise) @ rotation
            velocity = _uniform_like(
                velocity, self._reset_velocity_noise[0], self._reset_velocity_noise[1]
            )
            angular = _uniform_like(
                angular, self._reset_angular_noise[0], self._reset_angular_noise[1]
            )
            joints = joints + torch.empty_like(joints).uniform_(-0.1, 0.1)
            state = (position, rotation, velocity, angular, joints, state[5])

        if selected is None:
            self._state = state
            self._context = context
            self._frames = frames
            self._ep_step = torch.zeros(batch, dtype=torch.long, device=self.device)
            self._previous_action = torch.zeros((batch, self.mdp.num_joints), device=self.device)
        else:
            assert self._state is not None
            self._state = cast(
                State,
                tuple(old.index_copy(0, selected, new) for new, old in zip(state, self._state)),
            )
            self._context.index_copy_(0, selected, context)
            self._frames.index_copy_(0, selected, frames)
            self._ep_step.index_fill_(0, selected, 0)
            self._previous_action.index_fill_(0, selected, 0.0)

        assert self._state is not None
        self._normalized_context = self.mdp.normalize_context(self._context)
        if selected is None:
            obs = self.mdp.obs(self._state, self._previous_action, self._context, self._frames)
            self._obs_hist = obs[:, None, :].expand(-1, self.cfg.hist, -1).clone()
        else:
            selected_state = cast(State, tuple(item[selected] for item in self._state))
            obs = self.mdp.obs(
                selected_state,
                self._previous_action[selected],
                self._context[selected],
                self._frames[selected],
            )
            assert self._obs_hist is not None
            selected_obs = obs[:, None, :].expand(-1, self.cfg.hist, -1)
            self._obs_hist.index_copy_(0, selected, selected_obs)
        return torch.ones(batch, dtype=torch.bool, device=self.device)

    def reset_all(self) -> None:
        self._reset_batch(None)

    def _reward_term(
        self,
        state: State,
        frames: torch.Tensor,
        action: torch.Tensor,
        previous_action: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        return self.mdp.reward(state, frames, action, previous_action), self.mdp.soft_termination(
            state, frames
        )

    def _reward_term_critic_features(
        self,
        state: State,
        frames: torch.Tensor,
        normalized_context: torch.Tensor,
        reference_state: State,
        reference_body_state: tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor],
        action: torch.Tensor,
        previous_action: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        reward, dones, features = self.mdp.reward_term_critic_features_with_reference(
            state,
            frames,
            normalized_context,
            reference_state,
            reference_body_state,
            action,
            previous_action,
        )
        return reward, dones, features

    def _critic_input(
        self,
        state: State,
        frames: torch.Tensor,
        normalized_context: torch.Tensor,
        goal: torch.Tensor,
    ) -> torch.Tensor:
        return torch.cat((self.mdp.critic_features(state, frames, normalized_context), goal), -1)

    def _batched_critic_input(
        self,
        state: State,
        frames: torch.Tensor,
        normalized_context: torch.Tensor,
        goal: torch.Tensor,
    ) -> torch.Tensor:
        return self._critic_input_fn(state, frames, normalized_context, goal)

    @staticmethod
    def _resolve_optimizer_mode(
        mode: str, device: torch.device
    ) -> Literal["fused", "foreach", "single"]:
        """Resolve an optimizer implementation without silently changing device support."""
        if mode == "auto":
            # This matches the historical implementation: fused on CUDA, Adam's
            # platform-selected implementation everywhere else.
            return "fused" if device.type == "cuda" else "single"
        if mode == "fused" and device.type != "cuda":
            raise ValueError(
                f"fused optimizers require CUDA; device {device} requested fused explicitly"
            )
        return cast(Literal["foreach", "single"], mode)

    def _critic_forward(self, x: torch.Tensor) -> torch.Tensor:
        """Run the critic while folding input normalization into its first linear.

        ``(x - mean) / std @ W.T + b`` is algebraically identical to
        ``x @ (W / std).T + (b - W @ (mean / std))``. The latter reads the already
        contiguous concatenated critic input once and avoids two horizon-sized
        normalization temporaries before the first GEMM.
        """
        norm = self.critic.norm
        first = self.critic.net[0]
        assert isinstance(first, nn.Linear)
        inv_std = norm.std().reciprocal()
        normalized_weight = first.weight * inv_std
        shift = first.bias - torch.mv(first.weight, norm.mean * inv_std)

        def run(x: torch.Tensor) -> torch.Tensor:
            hidden = F.linear(x, normalized_weight, shift)
            for layer in self.critic.net[1:]:
                hidden = layer(hidden)
            return hidden

        amp_dtype = networks_module.AMP_DTYPE
        if amp_dtype is not None and x.device.type in ("cuda", "mps"):
            with torch.autocast(x.device.type, dtype=amp_dtype):
                hidden = run(x)
            return hidden.float().squeeze(-1)
        return run(x).squeeze(-1)

    def _critic_targets(
        self,
        values: torch.Tensor,
        rewards: torch.Tensor,
        dones: torch.Tensor,
    ) -> torch.Tensor:
        target = values[-1]
        targets: list[torch.Tensor] = []
        gamma, lam = self.cfg.gamma, self.cfg.lam
        for index in range(self.cfg.horizon - 1, -1, -1):
            target = rewards[index] + gamma * (1 - dones[index]) * (
                (1 - lam) * values[index + 1] + lam * target
            )
            targets.append(target)
        return torch.stack(targets[::-1])

    def _critic_loss(self, critic_input: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        return F.mse_loss(self._critic_forward(critic_input), targets)

    def _update_critic_norm(self, critic_input: torch.Tensor) -> None:
        """Apply the configured RunningNorm update cadence and sample budget."""
        if self.cfg.critic_norm_update == "off":
            return
        if self.iteration % self.cfg.critic_norm_interval != 0:
            return

        rows = critic_input.shape[0] * critic_input.shape[1]
        sample = self.cfg.critic_norm_subsample
        if self.cfg.critic_norm_update == "subsample" and rows > sample:
            # Sampling with replacement keeps the index generation entirely on-device and
            # avoids a host sync or a full randperm. For sample >= rows this is exactly a
            # full update, which makes acceleration switches easy to test.
            indices = torch.randint(rows, (sample,), device=critic_input.device)
            update_input = critic_input.reshape(-1, critic_input.shape[-1]).index_select(0, indices)
        else:
            update_input = critic_input
        self.critic.norm.update(update_input)

    def update(
        self,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, float]:
        if self._state is None:
            raise RuntimeError("imagination state has not been initialized")

        state = self._state
        context = self._context
        assert context is not None
        normalized_context = self._normalized_context
        assert normalized_context is not None
        frames = self._frames
        assert frames is not None
        previous_action = self._previous_action
        assert previous_action is not None
        obs_hist = self._obs_hist
        assert obs_hist is not None

        initial_state = state
        frames0 = frames

        # Materialize every reference frame once. Goals, observations, reward,
        # termination, and critic inputs then share these deterministic gathers.
        frame_offsets = torch.arange(
            self.cfg.horizon + 1, device=self.device, dtype=frames.dtype
        ).unsqueeze(-1)
        frame_sequence = frames0.unsqueeze(0) + frame_offsets
        critic_goals = self.mdp.goal(frame_sequence.flatten(), self.cfg.goal_frames).view(
            self.cfg.horizon + 1, self.cfg.batch, -1
        )
        goal = critic_goals[0]
        reference_state = cast(
            State,
            tuple(
                part.reshape(self.cfg.horizon + 1, self.cfg.batch, *part.shape[1:])
                for part in self.motion.ref_state(frame_sequence.flatten())
            ),
        )
        self._fused_scoring = self._fused_scoring and hasattr(self.motion, "body_state")
        reference_body_state = (
            tuple(
                part.reshape(self.cfg.horizon + 1, self.cfg.batch, *part.shape[1:])
                for part in self.motion.body_state(frame_sequence.flatten())
            )
            if self._fused_scoring
            else None
        )

        states: list[State] = []
        actions: list[torch.Tensor] = []
        previous_actions: list[torch.Tensor] = []

        self.critic.requires_grad_(False)
        for index in range(self.cfg.horizon):
            previous_actions.append(previous_action)
            action = self._imag_policy_fn(obs_hist, goal)
            if self._detach_frozen_wm:
                with torch.no_grad():
                    state = self._imag_state_fn(state, action, normalized_context)
            else:
                state = self._imag_state_fn(state, action, normalized_context)
            next_frames = frames0 + index + 1
            if hasattr(self.mdp, "obs_with_reference"):
                obs = self.mdp.obs_with_reference(
                    state,
                    action,
                    context,
                    next_frames,
                    reference_state[1][index + 1],
                )
            else:
                obs = self.mdp.obs(state, action, context, next_frames)
            obs_hist = torch.cat((obs_hist[:, 1:], obs.unsqueeze(1)), 1)
            goal = critic_goals[index + 1]
            previous_action = action
            states.append(state)
            actions.append(action)

        def flatten(parts: list[torch.Tensor]) -> torch.Tensor:
            return torch.stack(parts).flatten(0, 1)

        # Include the initial state so a single FK pass serves all scored rewards,
        # the soft-done curve, and all T + 1 critic feature rows.
        all_states = cast(
            State,
            tuple(
                torch.cat(
                    (
                        initial_state[index].unsqueeze(0),
                        torch.stack([item[index] for item in states]),
                    )
                ).flatten(0, 1)
                for index in range(6)
            ),
        )
        flat_actions = flatten(actions)
        if self.cfg.horizon == 1:
            flat_previous_actions = previous_actions[0]
        else:
            flat_previous_actions = torch.cat(
                (previous_actions[0].unsqueeze(0), torch.stack(actions[:-1])), 0
            ).flatten(0, 1)

        if self._fused_scoring:
            scored_frames = frame_sequence[1:].flatten()
            expanded_context = (
                normalized_context.unsqueeze(0).expand(self.cfg.horizon + 1, -1, -1).flatten(0, 1)
            )
            rewards, dones, critic_features = self._fused_score_fn(
                all_states,
                scored_frames,
                expanded_context,
                tuple(part.flatten(0, 1) for part in reference_state),
                tuple(part.flatten(0, 1) for part in reference_body_state)
                if reference_body_state is not None
                else None,
                flat_actions,
                flat_previous_actions,
            )
            rewards = rewards.view(self.cfg.horizon, self.cfg.batch)
            dones = dones.view(self.cfg.horizon, self.cfg.batch)
            critic_input = torch.cat((critic_features, critic_goals.flatten(0, 1)), -1).view(
                self.cfg.horizon + 1, self.cfg.batch, -1
            )
        else:
            rewards, dones = self._reward_fn(
                cast(
                    State,
                    tuple(
                        item[self.cfg.batch :].reshape(-1, *item.shape[1:]) for item in all_states
                    ),
                ),
                frame_sequence[1:].flatten(),
                flat_actions,
                flat_previous_actions,
            )
            rewards = rewards.view(self.cfg.horizon, self.cfg.batch)
            dones = dones.view(self.cfg.horizon, self.cfg.batch)
            critic_input = self._batched_critic_input(
                all_states,
                frame_sequence.flatten(),
                expanded_context := (
                    normalized_context.unsqueeze(0)
                    .expand(self.cfg.horizon + 1, -1, -1)
                    .flatten(0, 1)
                ),
                critic_goals.flatten(0, 1),
            )

        alive = torch.cumprod(1 - dones, 0)
        continuation = torch.cat((torch.ones(1, self.cfg.batch, device=self.device), alive[:-1]), 0)
        discount = self.cfg.gamma ** torch.arange(
            self.cfg.horizon, device=self.device, dtype=torch.float32
        ).unsqueeze(-1)
        objective = (discount * continuation * rewards).sum(0)
        survival = alive[-1]
        reward_sum = (continuation * rewards.detach()).sum(0)
        detached_rewards, detached_dones = rewards.detach(), dones.detach()
        if not self.cfg.no_critic:
            bootstrap = self._critic_forward(critic_input[-1]).detach()
            objective = objective + (self.cfg.gamma**self.cfg.horizon) * survival * (
                bootstrap * self._v_std + self._v_mean
            )

        loss = -objective.mean()
        self.opt_pi.zero_grad(set_to_none=True)
        loss.backward()
        grad_norm = nn.utils.clip_grad_norm_(self.pi.parameters(), 1.0)
        nn.utils.clip_grad_value_(self.pi.parameters(), 0.1)
        if self.cfg.no_sync:
            finite = torch.isfinite(grad_norm)
            for parameter in self.pi.parameters():
                if parameter.grad is not None:
                    parameter.grad.copy_(torch.where(finite, parameter.grad, 0.0))
            self.opt_pi.step()
        elif torch.isfinite(grad_norm):
            self.opt_pi.step()
        if self.pi_avg is not None:
            self.pi_avg.update_parameters(self.pi)
        self.critic.requires_grad_(True)

        value_loss = torch.zeros((), device=self.device)
        if not self.cfg.no_critic:
            self._update_critic_norm(critic_input)
            with torch.no_grad():
                values = self._critic_forward(critic_input) * self._v_std + self._v_mean
                targets = self._critic_targets_fn(values, detached_rewards, detached_dones)
                target_mean = targets.mean()
                target_std = targets.std().clamp(min=1e-2)
                if not self._v_init:
                    self._v_mean = target_mean.detach()
                    self._v_std = target_std.detach()
                    self._v_init = True
                else:
                    self._v_mean = (1 - self._v_ema) * self._v_mean + self._v_ema * target_mean
                    self._v_std = (
                        ((1 - self._v_ema) * self._v_std**2 + self._v_ema * target_std**2)
                        .sqrt()
                        .clamp(min=1e-2)
                    )
                targets = ((targets - self._v_mean) / self._v_std).clamp(-20.0, 20.0)
            # Critic regression covers the T rollout transitions; the bootstrap row
            # only contributes through the GAE recursion above.
            flat_input = critic_input[:-1].reshape(-1, critic_input.shape[-1])
            flat_targets = targets.reshape(-1)
            num_samples = min(flat_input.shape[0], flat_targets.shape[0])
            minibatch_size = num_samples // self.cfg.critic_minibatches
            if minibatch_size == 0:
                raise ValueError("critic_minibatches exceeds imagined transitions")
            for _ in range(self.cfg.critic_epochs):
                permutation = torch.randperm(num_samples, device=self.device)
                for index in range(self.cfg.critic_minibatches):
                    # narrow is a scalar-offset view and index_select creates only the
                    # contiguous minibatch needed by the MLP (rather than reindexing the
                    # complete horizon tensor once per epoch).
                    start = index * minibatch_size
                    indices = permutation.narrow(0, start, minibatch_size)
                    minibatch_input = flat_input.index_select(0, indices)
                    minibatch_targets = flat_targets[:num_samples].index_select(0, indices)
                    value_loss = self._critic_loss_fn(minibatch_input, minibatch_targets)
                    self.opt_v.zero_grad(set_to_none=True)
                    value_loss.backward()
                    nn.utils.clip_grad_norm_(self.critic.parameters(), 1.0)
                    self.opt_v.step()

        # Decide resets using the pre-rollout frame plus the completed horizon so a
        # clip never advances beyond its final motion-library index.
        start_frames = frames0
        next_frames = start_frames + self.cfg.horizon
        episode_steps = self._ep_step + self.cfg.horizon
        next_ep_steps = torch.minimum(
            episode_steps, torch.tensor(self.cfg.max_episode_steps, device=self.device)
        )
        clip_end = next_frames >= self.motion.clip_end[self.motion.clip_id[start_frames]]
        timeout = episode_steps >= self.cfg.max_episode_steps
        hard_done = detached_dones[-1] > 0.5
        reset_mask = hard_done | timeout | clip_end
        reset_count = float(reset_mask.float().mean())
        surviving = (~reset_mask).nonzero(as_tuple=False).squeeze(-1)

        # Persist surviving terminal states first, then replace reset rows. This
        # keeps the imagined batch fixed-size without any simulator reset path.
        old_state = self._state
        self._state = cast(State, tuple(item[surviving].detach() for item in state))
        self._obs_hist = obs_hist[surviving].detach()
        self._previous_action = previous_action[surviving].detach()
        self._frames = next_frames[surviving]
        self._ep_step = next_ep_steps[surviving]
        del old_state
        selected_reset = reset_mask.nonzero(as_tuple=False).squeeze(-1)
        if selected_reset.numel():
            self._reset_batch(selected_reset)
        self.imag_steps += self.cfg.batch * self.cfg.horizon

        imagined_reward = (reward_sum / self.cfg.horizon / self.mdp.max_step_reward).mean()
        return (
            loss.detach(),
            value_loss.detach(),
            imagined_reward,
            grad_norm.detach(),
            survival.mean().detach(),
            reset_count,
        )

    def lr_at(self, iteration: int) -> float:
        if iteration >= self.cfg.lr_decay_iters:
            return self.cfg.lr * 0.03
        return self.cfg.lr * (
            0.03 + 0.97 * 0.5 * (1 + math.cos(math.pi * iteration / self.cfg.lr_decay_iters))
        )

    def _checkpoint(self, include_optimizers: bool) -> dict[str, object]:
        policy_state = (
            self.pi_avg.module.state_dict() if self.pi_avg is not None else self.pi.state_dict()
        )
        checkpoint: dict[str, object] = {
            "iteration": self.iteration,
            "wall_time": self.wall_time,
            "imag_steps": self.imag_steps,
            "pi": policy_state,
            "critic": self.critic.state_dict(),
            "v_mean": self._v_mean.detach().cpu(),
            "v_std": self._v_std.detach().cpu(),
            "v_init": self._v_init,
        }
        if self.pi_avg is not None:
            checkpoint["pi_live"] = self.pi.state_dict()
        if include_optimizers:
            checkpoint.update(
                {
                    "opt_pi": self.opt_pi.state_dict(),
                    "opt_v": self.opt_v.state_dict(),
                }
            )
        return checkpoint

    def save(self, path: str | Path | None = None, include_optimizers: bool = True) -> Path:
        destination = Path(path) if path is not None else self.log_dir / "last.pt"
        destination.parent.mkdir(parents=True, exist_ok=True)
        torch.save(self._checkpoint(include_optimizers), destination)
        return destination

    def load(self, checkpoint_path: str | Path) -> None:
        checkpoint = torch.load(checkpoint_path, map_location=self.device, weights_only=True)
        if not isinstance(checkpoint, dict):
            raise TypeError("imagined learner checkpoint must be a mapping")
        if "pi" not in checkpoint or "critic" not in checkpoint:
            raise ValueError("imagined learner checkpoint lacks policy or critic state")
        if self.pi_avg is not None:
            if "pi_live" not in checkpoint:
                raise ValueError("resume requires pi_live for EMA policies")
            self.pi.load_state_dict(checkpoint["pi_live"])
            self.pi_avg.module.load_state_dict(checkpoint["pi"])
        else:
            self.pi.load_state_dict(checkpoint["pi"])
        self.critic.load_state_dict(checkpoint["critic"])
        if "opt_pi" not in checkpoint or "opt_v" not in checkpoint:
            raise ValueError("resume requires optimizer states")
        self.opt_pi.load_state_dict(checkpoint["opt_pi"])
        self.opt_v.load_state_dict(checkpoint["opt_v"])
        self._v_mean = checkpoint.get("v_mean", self._v_mean).to(self.device)
        self._v_std = checkpoint.get("v_std", self._v_std).to(self.device)
        self._v_init = bool(checkpoint.get("v_init", False))
        self.iteration = int(checkpoint.get("iteration", 0))
        self.wall_time = float(checkpoint.get("wall_time", 0.0))
        self.imag_steps = int(checkpoint.get("imag_steps", 0))
        self.reset_all()

    def train(self, resume: str | Path | None = None) -> dict[str, float | int | bool]:
        if resume is not None:
            self.load(resume)
        start_iteration = self.iteration
        logger = _SimpleLogger(
            max_iterations=self.cfg.iterations,
            start_iteration=start_iteration,
            log_dir=str(self.log_dir),
            backend=self.cfg.log_backend,
        )
        logger.start()
        log_path = self.log_dir / "train_log.csv"
        aggregate: dict[str, list[float]] = {
            key: [] for key in ("pi", "v", "ir", "gn", "surv", "reset")
        }
        last_metrics: dict[str, float | int] = {}
        try:
            with log_path.open("a", encoding="utf-8", newline="") as log_file:
                if start_iteration == 0:
                    log_file.write(",".join(_LOG_FIELDS) + "\n")
                train_start = time.time() - self.wall_time
                log_start = time.time()
                for iteration in range(start_iteration, self.cfg.iterations):
                    if self.cfg.compile and iteration == start_iteration:
                        logger.status("Compiling frozen-WM imagination update (one-off)")
                    lr = self.lr_at(iteration)
                    for optimizer in (self.opt_pi, self.opt_v):
                        for group in optimizer.param_groups:
                            group["lr"] = lr
                    result = self.update()
                    pi_loss, v_loss, imag_rew, grad_norm, survival, reset_frac = result
                    for name, metric in (
                        ("pi_loss", pi_loss),
                        ("v_loss", v_loss),
                        ("imag_rew", imag_rew),
                    ):
                        if not torch.isfinite(metric).all():
                            raise FloatingPointError(
                                f"non-finite {name} at iteration {iteration + 1}"
                            )
                    self.iteration = iteration + 1
                    values = (
                        float(pi_loss),
                        float(v_loss),
                        float(imag_rew),
                        float(grad_norm),
                        float(survival),
                        reset_frac,
                    )
                    for key, value in zip(("pi", "v", "ir", "gn", "surv", "reset"), values):
                        aggregate[key].append(value)
                    if self.iteration % self.cfg.log_every == 0:
                        elapsed = time.time() - log_start
                        it_per_s = self.cfg.log_every / elapsed if elapsed > 0 else 0.0
                        row: list[float | int] = [
                            self.iteration,
                            (time.time() - train_start) / 3600,
                            self.imag_steps,
                            self._mean(aggregate["pi"]),
                            self._mean(aggregate["v"]),
                            self._mean(aggregate["ir"]),
                            self._mean(aggregate["gn"]),
                            self._mean(aggregate["surv"]),
                            self._mean(aggregate["reset"]),
                            it_per_s,
                            lr,
                        ]
                        log_file.write(
                            ",".join(
                                f"{value:.6g}" if isinstance(value, float) else str(value)
                                for value in row
                            )
                            + "\n"
                        )
                        log_file.flush()
                        logger.step(self.iteration, row)
                        last_metrics = dict(zip(_LOG_FIELDS, row, strict=True))
                        aggregate = {key: [] for key in aggregate}
                        log_start = time.time()
                    if (
                        self.iteration % self.cfg.ckpt_every == 0
                        or self.iteration == self.cfg.iterations
                    ):
                        self.wall_time = time.time() - train_start
                        self.save()
                        numbered = self.save(
                            self.log_dir / f"ckpt_{self.iteration:06d}.pt",
                            include_optimizers=False,
                        )
                        logger.saved(str(numbered))
            self.wall_time = time.time() - train_start
            logger.finish()
            return {
                "completed": self.iteration >= self.cfg.iterations,
                "iteration": self.iteration,
                "imag_steps": self.imag_steps,
                "wall_time": self.wall_time,
                **last_metrics,
            }
        finally:
            logger.close()

    @staticmethod
    def _mean(values: list[float]) -> float:
        return sum(values) / len(values) if values else 0.0


def _uniform_like(x: torch.Tensor, low: torch.Tensor, high: torch.Tensor) -> torch.Tensor:
    shape = (1,) * (x.ndim - 1) + (-1,)
    lo, hi = low.view(shape), high.view(shape)
    return x + torch.empty_like(x).uniform_(0.0, 1.0) * (hi - lo) + lo


def _so3_exp(omega: torch.Tensor) -> torch.Tensor:
    # Local import avoids a task-to-algorithm module cycle at import time.
    from unisupermimic.rl.algos.supermimic.geometry import so3_exp

    return so3_exp(omega)


class _SimpleLogger:
    """Minimal non-Rich logger suitable for the standalone imagined task."""

    def __init__(
        self,
        *,
        max_iterations: int,
        start_iteration: int,
        log_dir: str,
        backend: str,
    ) -> None:
        self.max_iterations = max_iterations
        self.iteration = start_iteration
        self._writer = None
        self._status = "starting"
        self._start = time.time()
        if backend.lower() not in ("tensorboard", "none", "no_print"):
            raise ValueError(
                f"log_backend must be 'tensorboard', 'none', or 'no_print', got {backend!r}"
            )
        if backend.lower() == "tensorboard":
            try:
                from torch.utils.tensorboard import SummaryWriter

                self._writer = SummaryWriter(log_dir=log_dir)
            except ImportError:
                self._writer = None

    def start(self) -> None:
        print(f"G1SuperMimicImagined training: {self._status}", flush=True)

    def status(self, status: str) -> None:
        self._status = status
        print(status, flush=True)

    def step(self, iteration: int, row: list[float | int]) -> None:
        self.iteration = iteration
        print(
            f"iteration={iteration}/{self.max_iterations} "
            + " ".join(
                f"{name}={value:.6g}" if isinstance(value, float) else f"{name}={value}"
                for name, value in zip(_LOG_FIELDS[2:], row[2:], strict=True)
            ),
            flush=True,
        )
        if self._writer is not None:
            for name, value in zip(_LOG_FIELDS[2:], row[2:], strict=True):
                self._writer.add_scalar(name, value, iteration)

    def saved(self, path: str) -> None:
        print(f"saved {path}", flush=True)

    def finish(self) -> None:
        elapsed = time.time() - self._start
        print(f"finished iteration={self.iteration} wall_time={elapsed:.1f}s", flush=True)

    def close(self) -> None:
        if self._writer is not None:
            self._writer.close()
            self._writer = None


