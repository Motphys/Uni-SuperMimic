@dataclass
class ImaginedSuperMimicConfig:
    iterations: int = 320_000
    batch: int = 4096
    horizon: int = 32
    goal_frames: int = 10
    hist: int = 10
    z_dim: int = 32
    policy_hidden: tuple[int, ...] = (2048, 1024, 512, 256)
    critic_hidden: tuple[int, ...] = (256, 128)
    lr: float = 4e-4
    pi_opt: str = "muon"
    no_sync: bool = True
    pi_ema: float = 0.995
    gamma: float = 0.99
    lam: float = 0.95
    max_episode_steps: int = 500
    critic_epochs: int = 5
    critic_minibatches: int = 4
    no_critic: bool = False
    reset_noise: bool = True
    lr_decay_iters: int = 250_000
    ckpt_every: int = 2000
    log_every: int = 50
    log_backend: str = "tensorboard"
    seed: int = 0
    amp: str = "bf16"
    compile: bool = True
    test_hidden_dims: tuple[int, ...] | None = None

    def __post_init__(self) -> None:
        if self.batch <= 0 or self.horizon <= 0 or self.hist <= 0:
            raise ValueError("batch, horizon, and hist must be positive")
        if self.gamma <= 0 or self.gamma >= 1:
            raise ValueError("gamma must be in (0, 1)")
        if self.lam < 0 or self.lam > 1:
            raise ValueError("lam must be in [0, 1]")
        if self.pi_opt not in ("adam", "muon"):
            raise ValueError(f"pi_opt must be 'adam' or 'muon', got {self.pi_opt!r}")
        if self.amp not in ("none", "bf16"):
            raise ValueError(f"amp must be 'none' or 'bf16', got {self.amp!r}")
        if self.critic_minibatches <= 0:
            raise ValueError("critic_minibatches must be positive")
        if self.test_hidden_dims is not None and not self.test_hidden_dims:
            raise ValueError("test_hidden_dims must be nonempty when provided")
        if self.iterations <= 0:
            raise ValueError("iterations must be positive")
        if self.critic_epochs < 0:
            raise ValueError("critic_epochs cannot be negative")
        if self.lr <= 0:
            raise ValueError("lr must be positive")
        if self.max_episode_steps <= 0:
            raise ValueError("max_episode_steps must be positive")


