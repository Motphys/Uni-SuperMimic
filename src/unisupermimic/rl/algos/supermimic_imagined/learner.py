"""Pure-imagination actor-critic with a frozen differentiable SuperMimic model.

There is intentionally no environment, replay buffer, world-model update, or
real-simulator rollout in this learner. Every training transition is generated by
the frozen world model, and the policy gradient backpropagates through its graph.
"""

